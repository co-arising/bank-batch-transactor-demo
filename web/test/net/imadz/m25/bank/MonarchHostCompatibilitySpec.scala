import java.nio.charset.StandardCharsets.UTF_8
import scala.concurrent.Future
import scala.concurrent.duration._

/** Real Bank web application.conf + dependency reference.conf, with only runtime
  * isolation overrides. No remoting listener, LevelDB directory or Play server.
  */
class MonarchHostCompatibilitySpec extends ScalaTestWithActorTestKit(
  ConfigFactory.parseString("""
    akka.actor.provider = local
    akka.actor.allow-java-serialization = off
    akka.remote.artery.canonical.port = 0
    akka.cluster.seed-nodes = []
    akka.persistence.journal.plugin = "akka.persistence.testkit.journal"
    akka.persistence.snapshot-store.plugin = "akka.persistence.no-snapshot-store"
    akka.persistence.testkit.events.serialize = true
    akka.actor.testkit.typed.single-expect-default = 10s
  """).withFallback(PersistenceTestKitPlugin.config).withFallback(ConfigFactory.load())
) with AnyWordSpecLike {

  private implicit val ec: scala.concurrent.ExecutionContext = system.executionContext
  private val serialization = SerializationExtension(system)
  private val journal = PersistenceTestKit(system)
  private val bytes = Array[Byte](0, 1, -1, -128)

  private def assertEvent(actual: AnyRef, expected: PersistentMonarch.Event): Unit = (actual, expected) match {
    case (read: PersistentMonarch.RunStarted, written: PersistentMonarch.RunStarted) =>
      read.runId shouldBe written.runId
      read.stageCursors shouldBe written.stageCursors
      read.initialSnapshot.toList shouldBe written.initialSnapshot.toList
    case (read: PersistentMonarch.StageDone, written: PersistentMonarch.StageDone) =>
      read.cursor shouldBe written.cursor
      read.timestamp shouldBe written.timestamp
      read.metadata shouldBe written.metadata
      read.snapshot.toList shouldBe written.snapshot.toList
    case (read: PersistentMonarch.StageResolved, written: PersistentMonarch.StageResolved) =>
      read.cursor shouldBe written.cursor
      read.timestamp shouldBe written.timestamp
      read.code shouldBe written.code
      read.errorCode shouldBe written.errorCode
      read.detail shouldBe written.detail
      read.snapshot.toList shouldBe written.snapshot.toList
    case _ => actual shouldBe expected
  }

  private def pipeline(ack: AckResult = AckReceived): SubBatchPipeline[String, String] =
    SubBatchPipeline[String, String](
      fileGen = (_, _) => Future.successful(GeneratedFile("/tmp/host.dat", "host.dat", 4L, "dat")),
      upload = (_, _) => Future.successful(UploadReceipt("/remote/host.dat", 4L, 1L)),
      waitAck = (_, _) => Future.successful(ack),
      pollResp = _ => Future.successful(ResponseReady(ResponseFile("/tmp/response.dat", "response.dat", 4L, bytes))),
      parse = (_, _) => Future.successful(Seq("OK")),
      classify = (_, items) => Future.successful(items.map(i => Success[String](i, "OK")))
    )

  "Monarch 0.2.1 in the Bank web host" should {
    "select protobuf for every persistent event under merged host bindings" in {
      // Ensures this is the web host merge, not only the library reference.conf.
      system.settings.config.getString("akka.actor.serialization-bindings.\"net.imadz.m25.proto.bank_chain.BankChainStateProto\"") shouldBe "proto"
      system.settings.config.getBoolean("akka.persistence.testkit.events.serialize") shouldBe true
      val events: Seq[PersistentMonarch.Event] = Seq(
        PersistentMonarch.RunStarted("host", Vector("load#0"), bytes),
        PersistentMonarch.StageDone("load#0", 1L, Map("source" -> "host"), bytes),
        PersistentMonarch.StageResolved("load#0", 2L, Some("R"), "RESOLVED", "detail", bytes),
        PersistentMonarch.RunCompleted("host"),
        PersistentMonarch.RunFailedEvt("load#0", "failure"),
        PersistentMonarch.RunPlanExtended(Vector("load#0", "post#1"))
      )
      events.foreach { event =>
        val serializer = serialization.findSerializerFor(event)
        serializer shouldBe a[MonarchSerializer]
        serializer.identifier shouldBe 77102121
        Serializers.manifestFor(serializer, event) shouldBe "E1"
        assertEvent(serialization.deserialize(serializer.toBinary(event), serializer.identifier, "E1").get, event)
      }
    }

    "read legacy JSON and CBOR records by stored serializer id and class manifest" in {
      // Literal retained-0.2 event shapes, NOT bytes generated by the new writer.
      // Akka 2.6.20 stock IDs are JSON=31 and CBOR=33. These fixtures are format
      // compatibility evidence, not records recovered from a historical Bank DB.
      val prefix = "net.imadz.monarch.persistence.PersistentMonarch$"
      val fixtures = Seq(
        ("RunStarted",
          """{"runId":"legacy-run","stageCursors":["load#0","post#1"],"initialSnapshot":"AAH/gA=="}""",
          "bf6572756e49646a6c65676163792d72756e6c7374616765437572736f72739f666c6f6164233066706f73742331ff6f696e697469616c536e617073686f74440001ff80ff",
          PersistentMonarch.RunStarted("legacy-run", Vector("load#0", "post#1"), bytes)),
        ("StageDone",
          """{"cursor":"load#0","timestamp":1700000000000,"metadata":{"source":"legacy"},"snapshot":"AAH/gA=="}""",
          "bf66637572736f72666c6f616423306974696d657374616d701b0000018bcfe56800686d65746164617461bf66736f75726365666c6567616379ff68736e617073686f74440001ff80ff",
          PersistentMonarch.StageDone("load#0", 1700000000000L, Map("source" -> "legacy"), bytes)),
        ("RunCompleted", """{"runId":"legacy-run"}""",
          "bf6572756e49646a6c65676163792d72756eff",
          PersistentMonarch.RunCompleted("legacy-run")),
        ("RunFailedEvt", """{"cursor":"post#1","reason":"insufficient-funds"}""",
          "bf66637572736f7266706f7374233166726561736f6e72696e73756666696369656e742d66756e6473ff",
          PersistentMonarch.RunFailedEvt("post#1", "insufficient-funds"))
      )
      system.settings.config.getInt("akka.actor.serialization-identifiers.jackson-json") shouldBe 31
      system.settings.config.getInt("akka.actor.serialization-identifiers.jackson-cbor") shouldBe 33
      val allowed = system.settings.config.getStringList("akka.serialization.jackson.allowed-class-prefix")
      fixtures.foreach { case (name, json, cborHex, expected) =>
        allowed.contains(prefix + name) shouldBe true
        assertEvent(serialization.deserialize(json.getBytes(UTF_8), 31, prefix + name).get, expected)
        val cbor = cborHex.grouped(2).map(Integer.parseInt(_, 16).toByte).toArray
        assertEvent(serialization.deserialize(cbor, 33, prefix + name).get, expected)
      }
    }

    "complete WebChain with the existing plain RunObserver and a committed final snapshot" in {
      val notifications = testKit.createTestProbe[Either[ChainExecutionActor.BankState, String]]()
      // Match the service's existing observer API, not DurableRunObserver.
      // One probe also pins final snapshot delivery before run completion.
      val observer = new RunObserver[ChainExecutionActor.BankState] {
        override def onStageComplete(cursor: String, metadata: Map[String, String], snapshot: ChainExecutionActor.BankState): Unit = notifications.ref ! Left(snapshot)
        override def onCompleted(runId: String): Unit = notifications.ref ! Right(runId)
      }
      val pid = PersistenceId(ChainExecutionActor.EntityTypeName, "bank-host-recharge-r1-b0")
      val ref = testKit.spawn(WebChain.behavior(pid, pipeline(), observer))
      val replies = testKit.createTestProbe[PersistentMonarch.RunReply]()
      val initial = BankChainState[String, String]("bank-host-recharge-r1-b0", "recharge", Seq("c1"))
      ref ! WebChain.Wrapped(PersistentMonarch.StartRun("host-web", initial, replies.ref))
      replies.expectMessage(PersistentMonarch.Accepted("host-web"))
      val snapshots = notifications.receiveMessages(6).map { message =>
        message.isLeft shouldBe true
        message.swap.toOption.get
      }
      notifications.expectMessage(Right("host-web"))
      snapshots.last.classifications shouldBe Some(Seq(Success[String]("c1", "OK")))
      val events = journal.persistedInStorage(pid.id)
      events should have size 8
      events.last shouldBe PersistentMonarch.RunCompleted("host-web")
      val latest = events.foldLeft(Option.empty[Array[Byte]])((previous, event) => LedgerRecovery.snapshotFromEvent(event, previous))
      LedgerRecovery.rebuild(Seq(("host", "recharge", 1, 0, 1L, latest))).seen should contain(("recharge", "c1"))
      testKit.stop(ref)
    }

    "retain WebChain's fail-stop semantics without a failure policy" in {
      val failed = testKit.createTestProbe[(String, String)]()
      val completed = testKit.createTestProbe[String]()
      val observer = new RunObserver[ChainExecutionActor.BankState] {
        override def onFailed(runId: String, cursor: String, reason: String): Unit = failed.ref ! ((runId, reason))
        override def onCompleted(runId: String): Unit = completed.ref ! runId
      }
      val pid = PersistenceId(ChainExecutionActor.EntityTypeName, "bank-host-failure-r1-b0")
      val ref = testKit.spawn(WebChain.behavior(pid, pipeline(AckRejected("rejected")), observer))
      val replies = testKit.createTestProbe[PersistentMonarch.RunReply]()
      ref ! WebChain.Wrapped(PersistentMonarch.StartRun("host-failure", BankChainState[String, String]("b", "recharge", Seq("c1")), replies.ref))
      replies.expectMessage(PersistentMonarch.Accepted("host-failure"))
      val (runId, reason) = failed.receiveMessage()
      runId shouldBe "host-failure"
      reason should include("ACK_REJECTED")
      val events = journal.persistedInStorage(pid.id)
      events should have size 4
      events.last shouldBe a[PersistentMonarch.RunFailedEvt]
      events.exists(_.isInstanceOf[PersistentMonarch.StageResolved]) shouldBe false
      completed.expectNoMessage(200.millis)
      testKit.stop(ref)
    }
  }
}
